import 'package:mix/mix.dart';

/// Fox UI alias for a generic Mix style.
typedef SStyle<S extends Spec<S>> = Style<S>;

/// Fox UI alias for a resolved Mix style spec.
typedef SStyleSpec<S extends Spec<S>> = StyleSpec<S>;

/// Fox UI alias for Mix's [BoxSpec].
typedef SBoxSpec = BoxSpec;

/// Fox UI alias for Mix's [BoxStyler].
typedef SBoxStyle = BoxStyler;

/// Fox UI alias for Mix's [FlexBoxSpec].
typedef SFlexBoxSpec = FlexBoxSpec;

/// Fox UI alias for Mix's [FlexBoxStyler].
typedef SFlexBoxStyle = FlexBoxStyler;

/// Fox UI alias for styling SRowBox.
typedef SRowBoxStyle = FlexBoxStyler;

/// Fox UI alias for styling SColumnBox.
typedef SColumnBoxStyle = FlexBoxStyler;

/// Fox UI alias for Mix's [TextSpec].
typedef STextSpec = TextSpec;

/// Fox UI alias for Mix's [TextStyler].
typedef STextStyle = TextStyler;

/// Fox UI alias for Mix's [IconSpec].
typedef SIconSpec = IconSpec;

/// Fox UI alias for Mix's [IconStyler].
typedef SIconStyle = IconStyler;

/// Fox UI alias for Mix's [ImageSpec].
typedef SImageSpec = ImageSpec;

/// Fox UI alias for Mix's [ImageStyler].
typedef SImageStyle = ImageStyler;

/// Fox UI alias for styling SPressable.
typedef SPressableStyle = BoxStyler;

/// Fox UI alias for Mix's [StackBoxSpec].
typedef SStackSpec = StackBoxSpec;

/// Fox UI alias for Mix's [StackBoxStyler].
typedef SStackStyle = StackBoxStyler;
